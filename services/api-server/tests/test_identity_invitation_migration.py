from pathlib import Path


MIGRATION = (
    Path(__file__).parents[1]
    / "db"
    / "migrations"
    / "0016_identity_invitation_lifecycle.sql"
)
WRAPPER = (
    Path(__file__).parents[3]
    / "supabase"
    / "migrations"
    / "0016_identity_invitation_lifecycle.sql"
)


def test_invitation_migration_is_hash_only_replay_safe_and_tenant_scoped() -> None:
    sql = MIGRATION.read_text(encoding="utf-8")
    lowered = sql.lower()

    assert "CREATE TABLE IF NOT EXISTS tenant_invitations" in sql
    assert "CREATE TABLE IF NOT EXISTS identity_invitation_token_index" in sql
    assert "CREATE TABLE IF NOT EXISTS tenant_identity_access_events" in sql
    assert "token_hash" in sql
    assert "plain_token" not in lowered
    assert "access_token" not in lowered
    assert "UNIQUE (token_hash)" in sql
    assert "status IN ('pending', 'accepted', 'revoked', 'expired')" in sql
    assert "ENABLE ROW LEVEL SECURITY" in sql
    assert "FORCE ROW LEVEL SECURITY" in sql
    assert "realytics.tenant_id" in sql
    assert "event_payload" in sql
    assert sql.count("AS PERMISSIVE") == 2
    assert "AS RESTRICTIVE" not in sql


def test_supabase_invitation_wrapper_is_generated() -> None:
    rendered = WRAPPER.read_text(encoding="utf-8")
    assert "GENERATED BY services/api-server/scripts/render_supabase_migrations.py" in rendered
    assert "0016_identity_invitation_lifecycle.sql" in rendered
    assert "CREATE TABLE IF NOT EXISTS tenant_invitations" in rendered
