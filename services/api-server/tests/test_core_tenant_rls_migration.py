from pathlib import Path


MIGRATION = Path(__file__).parents[1] / "db" / "migrations" / "0013_core_tenant_rls.sql"
WRAPPER = Path(__file__).parents[3] / "supabase" / "migrations" / "0013_core_tenant_rls.sql"


def test_core_tenant_rls_is_deny_by_default_and_transaction_scoped() -> None:
    sql = MIGRATION.read_text(encoding="utf-8")
    assert "ENABLE ROW LEVEL SECURITY" in sql
    assert "FORCE ROW LEVEL SECURITY" in sql
    assert "AS RESTRICTIVE" in sql
    assert "realytics.tenant_id" in sql
    assert "NULLIF(current_setting" in sql
    assert "WITH CHECK" in sql
    assert "tenant_memberships" in sql


def test_supabase_wrapper_is_generated_from_authoritative_source() -> None:
    sql = WRAPPER.read_text(encoding="utf-8")
    assert "GENERATED BY services/api-server/scripts/render_supabase_migrations.py" in sql
    assert "0013_core_tenant_rls.sql" in sql
    assert "CREATE POLICY" in sql
