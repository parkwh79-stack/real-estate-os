from pathlib import Path


ROOT = Path(__file__).resolve().parents[3]
MIGRATION_NAME = "20260731093559_calculation_run_tenant_read_index.sql"


def test_calculation_run_tenant_read_index_is_tenant_first_and_deployable():
    source = (
        ROOT
        / "services"
        / "api-server"
        / "db"
        / "migrations"
        / MIGRATION_NAME
    )
    rendered = ROOT / "supabase" / "migrations" / MIGRATION_NAME
    source_sql = source.read_text(encoding="utf-8")
    rendered_sql = rendered.read_text(encoding="utf-8")

    expected_columns = (
        "tenant_id,\n"
        "        project_id,\n"
        "        engine_key,\n"
        "        created_at DESC,\n"
        "        calculation_run_id DESC"
    )
    assert "idx_calculation_runs_tenant_project_engine_latest" in source_sql
    assert expected_columns in source_sql
    assert "calculation_run_index_postflight" in source_sql
    assert (
        "GENERATED BY services/api-server/scripts/render_supabase_migrations.py"
        in rendered_sql
    )
    assert source_sql.strip() in rendered_sql
