from __future__ import annotations

"""Render the authoritative REALYTICS migrations for Supabase CLI deployment.

The SQL in ``db/migrations`` remains the only hand-edited source.  This bridge
adds the Supabase-specific schema boundary and a checksum ledger without
changing the authoritative SQL.  Supabase CLI independently owns its
``supabase_migrations.schema_migrations`` deployment ledger.
"""

import argparse
import hashlib
import sys
from pathlib import Path
from typing import Iterable, Mapping, Sequence


API_ROOT = Path(__file__).resolve().parents[1]
REPOSITORY_ROOT = Path(__file__).resolve().parents[3]
SOURCE_MIGRATIONS_DIR = API_ROOT / "db" / "migrations"
SUPABASE_MIGRATIONS_DIR = REPOSITORY_ROOT / "supabase" / "migrations"
GENERATED_MARKER = "-- GENERATED BY services/api-server/scripts/render_supabase_migrations.py"


def normalize_sql(text: str) -> str:
    """Canonicalize host line endings while preserving all other source bytes."""

    return text.replace("\r\n", "\n").replace("\r", "\n")


def source_text(path: Path) -> str:
    """Read a source migration using the runtime migration checksum contract."""

    return normalize_sql(path.read_text(encoding="utf-8"))


def source_checksum(path: Path) -> str:
    """Return the SHA-256 identity used by ``db.postgres``."""

    return hashlib.sha256(source_text(path).encode("utf-8")).hexdigest()


def _sql_literal(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def render_migration(path: Path) -> str:
    """Wrap one authoritative migration with Supabase deployment safeguards."""

    filename = path.name
    checksum = source_checksum(path)
    authoritative_sql = source_text(path).rstrip("\n")
    filename_literal = _sql_literal(filename)
    checksum_literal = _sql_literal(checksum)

    return f"""{GENERATED_MARKER}
-- DO NOT EDIT: update services/api-server/db/migrations/{filename} and run the generator again.
-- Authoritative filename: {filename}
-- Authoritative normalized SHA-256: {checksum}
--
-- Ledger ownership:
--   * Supabase CLI owns supabase_migrations.schema_migrations.
--   * REALYTICS owns realytics.schema_migrations and records source identity.

SET statement_timeout = '10min';
SET lock_timeout = '10s';

CREATE SCHEMA IF NOT EXISTS extensions;
REVOKE CREATE ON SCHEMA extensions FROM PUBLIC;

CREATE EXTENSION IF NOT EXISTS postgis WITH SCHEMA extensions;

DO $realytics_postgis_schema$
DECLARE
    installed_schema TEXT;
BEGIN
    SELECT namespace.nspname
      INTO installed_schema
      FROM pg_extension AS extension
      JOIN pg_namespace AS namespace
        ON namespace.oid = extension.extnamespace
     WHERE extension.extname = 'postgis';

    IF installed_schema IS DISTINCT FROM 'extensions' THEN
        RAISE EXCEPTION
            'PostGIS must be installed in the extensions schema (found: %)',
            COALESCE(installed_schema, '<not installed>');
    END IF;
END;
$realytics_postgis_schema$;

CREATE SCHEMA IF NOT EXISTS realytics;
REVOKE ALL ON SCHEMA realytics
    FROM PUBLIC, anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA realytics
    REVOKE ALL ON TABLES
    FROM PUBLIC, anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA realytics
    REVOKE ALL ON SEQUENCES
    FROM PUBLIC, anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA realytics
    REVOKE ALL ON FUNCTIONS
    FROM PUBLIC, anon, authenticated, service_role;
REVOKE ALL ON ALL TABLES IN SCHEMA realytics
    FROM PUBLIC, anon, authenticated, service_role;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA realytics
    FROM PUBLIC, anon, authenticated, service_role;
REVOKE ALL ON ALL FUNCTIONS IN SCHEMA realytics
    FROM PUBLIC, anon, authenticated, service_role;

-- Keep current_schema() on realytics while explicitly placing the temporary
-- schema last. pg_catalog remains implicitly searched before these entries.
SET search_path TO realytics, extensions, public, pg_temp;

CREATE TABLE IF NOT EXISTS realytics.schema_migrations (
    version TEXT PRIMARY KEY,
    checksum TEXT NOT NULL,
    applied_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
REVOKE ALL ON TABLE realytics.schema_migrations
    FROM PUBLIC, anon, authenticated, service_role;

DO $realytics_source_checksum$
DECLARE
    recorded_checksum TEXT;
BEGIN
    SELECT checksum
      INTO recorded_checksum
      FROM realytics.schema_migrations
     WHERE version = {filename_literal};

    IF FOUND AND recorded_checksum <> {checksum_literal} THEN
        RAISE EXCEPTION
            'REALYTICS migration checksum conflict for %',
            {filename_literal}
            USING DETAIL = format(
                'database=%, repository=%',
                recorded_checksum,
                {checksum_literal}
            ),
            HINT = 'Create a new authoritative migration; never edit an applied migration.';
    END IF;
END;
$realytics_source_checksum$;

-- BEGIN AUTHORITATIVE REALYTICS SQL: {filename}
{authoritative_sql}
-- END AUTHORITATIVE REALYTICS SQL: {filename}

REVOKE ALL ON ALL TABLES IN SCHEMA realytics
    FROM PUBLIC, anon, authenticated, service_role;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA realytics
    FROM PUBLIC, anon, authenticated, service_role;
REVOKE ALL ON ALL FUNCTIONS IN SCHEMA realytics
    FROM PUBLIC, anon, authenticated, service_role;

INSERT INTO realytics.schema_migrations (version, checksum)
VALUES ({filename_literal}, {checksum_literal})
ON CONFLICT (version) DO NOTHING;
"""


def discover_sources(source_dir: Path = SOURCE_MIGRATIONS_DIR) -> list[Path]:
    """Return authoritative migrations in deployment order."""

    return sorted(
        path
        for path in source_dir.glob("*.sql")
        if path.is_file()
    )


def expected_outputs(
    source_dir: Path = SOURCE_MIGRATIONS_DIR,
) -> dict[str, str]:
    """Build the deterministic filename-to-wrapper mapping."""

    sources = discover_sources(source_dir)
    if not sources:
        raise RuntimeError(f"No authoritative migrations found in {source_dir}")
    return {path.name: render_migration(path) for path in sources}


def _generated_files(output_dir: Path) -> Iterable[Path]:
    if not output_dir.exists():
        return ()
    return (
        path
        for path in output_dir.glob("*.sql")
        if path.is_file()
        and normalize_sql(path.read_text(encoding="utf-8")).startswith(
            GENERATED_MARKER
        )
    )


def sync_migrations(
    *,
    source_dir: Path = SOURCE_MIGRATIONS_DIR,
    output_dir: Path = SUPABASE_MIGRATIONS_DIR,
    check: bool = False,
) -> tuple[str, ...]:
    """Write wrappers, or report drift without writing when ``check`` is true."""

    expected = expected_outputs(source_dir)
    drift: list[str] = []

    for filename, rendered in expected.items():
        target = output_dir / filename
        if not target.exists():
            drift.append(f"missing:{filename}")
            continue
        current = normalize_sql(target.read_text(encoding="utf-8"))
        if current != rendered:
            drift.append(f"changed:{filename}")

    stale = sorted(
        path
        for path in _generated_files(output_dir)
        if path.name not in expected
    )
    drift.extend(f"stale:{path.name}" for path in stale)

    if check:
        return tuple(drift)

    output_dir.mkdir(parents=True, exist_ok=True)
    for filename, rendered in expected.items():
        target = output_dir / filename
        if (
            not target.exists()
            or normalize_sql(target.read_text(encoding="utf-8")) != rendered
        ):
            target.write_text(rendered, encoding="utf-8", newline="\n")
    for path in stale:
        path.unlink()
    return ()


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=(
            "Render authoritative REALYTICS SQL as Supabase CLI migrations."
        )
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if generated migrations are missing, changed, or stale",
    )
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    args = _parser().parse_args(argv)
    drift = sync_migrations(check=args.check)
    if drift:
        print(
            "Supabase migration wrappers are out of date: " + ", ".join(drift),
            file=sys.stderr,
        )
        return 1
    if args.check:
        print("Supabase migration wrappers are current.")
    else:
        print(
            f"Rendered {len(expected_outputs())} Supabase migration wrappers."
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
